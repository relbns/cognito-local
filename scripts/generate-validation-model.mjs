#!/usr/bin/env node
// Derives src/server/validation/cognitoIdpModel.generated.ts from the botocore cognito-idp service model.
// Usage: node scripts/generate-validation-model.mjs [--model <service-2.json>]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BOTOCORE_VERSION = "1.43.116";
const MODEL_PATH = "botocore/data/cognito-idp/2016-04-18/service-2.json";
const MODEL_URL = `https://raw.githubusercontent.com/boto/botocore/${BOTOCORE_VERSION}/${MODEL_PATH}`;
const MODEL_SHA256 =
  "3bed2e7bf2d62434576b3c4ddfbc410aa74a0104a1cfda6c493926e9c1482555";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(
  ROOT,
  "src/server/validation/cognitoIdpModel.generated.ts",
);

const loadModel = async () => {
  const flag = process.argv.indexOf("--model");
  if (flag !== -1) return readFileSync(process.argv[flag + 1], "utf8");
  const response = await fetch(MODEL_URL);
  if (!response.ok) throw new Error(`GET ${MODEL_URL}: ${response.status}`);
  return response.text();
};

const javaPatternToRegExp = (pattern) => {
  const dotAll = pattern.startsWith("(?s)");
  return new RegExp(
    `^(?:${dotAll ? pattern.slice(4) : pattern})$`,
    dotAll ? "us" : "u",
  );
};

const deriveShape = (shape) => {
  const out = { type: shape.document ? "document" : shape.type };
  switch (out.type) {
    case "structure":
      out.members = Object.fromEntries(
        Object.entries(shape.members).map(([name, m]) => [name, m.shape]),
      );
      if (shape.required?.length) out.required = shape.required;
      break;
    case "list":
      out.member = shape.member.shape;
      break;
    case "map":
      out.key = shape.key.shape;
      out.value = shape.value.shape;
      break;
    case "string":
      if (shape.pattern !== undefined) {
        javaPatternToRegExp(shape.pattern);
        out.pattern = shape.pattern;
      }
      if (shape.enum) out.enum = shape.enum;
      break;
  }
  if (["string", "list", "map", "blob", "integer", "long"].includes(out.type)) {
    if (shape.min !== undefined) out.min = shape.min;
    if (shape.max !== undefined) out.max = shape.max;
  }
  if (shape.sensitive) out.sensitive = true;
  return out;
};

const main = async () => {
  const text = await loadModel();
  const sha256 = createHash("sha256").update(text).digest("hex");
  if (!process.argv.includes("--model") && sha256 !== MODEL_SHA256) {
    throw new Error(`model checksum ${sha256} does not match ${MODEL_SHA256}`);
  }
  const model = JSON.parse(text);

  const operations = {};
  const reachable = new Set();
  const visit = (name) => {
    if (reachable.has(name)) return;
    reachable.add(name);
    const shape = model.shapes[name];
    if (shape.members) for (const m of Object.values(shape.members)) visit(m.shape);
    if (shape.member) visit(shape.member.shape);
    if (shape.key) visit(shape.key.shape);
    if (shape.value) visit(shape.value.shape);
  };
  for (const name of Object.keys(model.operations).sort()) {
    const input = model.operations[name].input?.shape;
    if (!input) continue;
    operations[name] = input;
    visit(input);
  }

  const shapeLines = [...reachable]
    .sort()
    .map((name) => `  ${name}: ${JSON.stringify(deriveShape(model.shapes[name]))},`);
  const operationLines = Object.entries(operations).map(
    ([name, input]) => `  ${name}: ${JSON.stringify(input)},`,
  );

  const source = `/*! Derived from botocore ${BOTOCORE_VERSION} ${MODEL_PATH}, Copyright Amazon.com, Inc. or its affiliates.
 Licensed under the Apache License 2.0 (licenses/cognito-idp-model). Generated by scripts/generate-validation-model.mjs. */
import type { ModelShape } from "./modelShape";

export const MODEL_SOURCE = {
  botocore: ${JSON.stringify(BOTOCORE_VERSION)},
  path: ${JSON.stringify(MODEL_PATH)},
  sha256: ${JSON.stringify(sha256)},
};

export const OPERATION_INPUTS: Record<string, string> = {
${operationLines.join("\n")}
};

export const SHAPES: Record<string, ModelShape> = {
${shapeLines.join("\n")}
};
`;
  writeFileSync(OUTPUT, source);
  console.log(
    `wrote ${OUTPUT}: ${operationLines.length} operations, ${shapeLines.length} shapes, ${source.length} bytes`,
  );
};

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
